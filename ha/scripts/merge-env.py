#!/usr/bin/env python3
"""Build Server 2's HA .env: Server 1's prod .env (identity, keys, URLs) +
Server 2's own infra keys (container names, ports, local DB/MinIO creds, tag).
Usage: merge-env.py <s1.env> <old-s2.env> <out.env> <ha_database_url_file> [ha_overrides_file]
The optional overrides file (/root/unbottled/.ha-overrides, written by
ha/failover/ha-failover.sh promote) holds KEY=VALUE lines that win over both
inputs, e.g. HA_REDIS_URL / HA_S3_ENDPOINT / HA_TASK_RUNNER after a failover.
Prints only key NAMES, never values."""
import sys, re
s1, s2old, out, dburl_file = sys.argv[1:5]
overrides_file = sys.argv[5] if len(sys.argv) > 5 else None
KEEP_FROM_S2 = ["APP_CONTAINER_NAME","APP_HOST_PORT","APP_WS_HOST_PORT","APP_STOP_GRACE_PERIOD",
  "DOCKER_IMAGE_TAG","MINIO_CONTAINER_NAME","MINIO_INIT_CONTAINER_NAME","MINIO_ROOT_USER",
  "MINIO_ROOT_PASSWORD","PG_CONTAINER_NAME","PG_DATA_HOST_DIR","POSTGRES_DB","POSTGRES_USER",
  "POSTGRES_PASSWORD","REDIS_CONTAINER_NAME","STREAM_DRAIN_TIMEOUT_MS","UPLOADS_HOST_DIR"]
def parse(p):
    d={}
    for line in open(p):
        m=re.match(r'^([A-Za-z_][A-Za-z0-9_]*)=(.*)$', line.rstrip("\n"))
        if m: d[m.group(1)]=m.group(2)
    return d
a=parse(s1); b=parse(s2old)
ov=parse(overrides_file) if overrides_file else {}
lines=[]
for line in open(s1):
    if line.startswith("# ---- "):   # our own section headers (re-merge in place)
        continue
    m=re.match(r'^([A-Za-z_][A-Za-z0-9_]*)=', line)
    if m and (m.group(1) in KEEP_FROM_S2 or m.group(1)=="HA_DATABASE_URL" or m.group(1) in ov):
        continue
    lines.append(line.rstrip("\n"))
while lines and not lines[-1].strip():   # no blank-line pile-up on re-merge
    lines.pop()
lines.append("")
lines.append("# ---- Server 2 overrides (generated by ha merge-env.py; base = Server 1 /unbottled/.env) ----")
missing=[]
for k in KEEP_FROM_S2:
    if k in b: lines.append(f"{k}={b[k]}")
    else: missing.append(k)
lines.append("HA_DATABASE_URL="+open(dburl_file).read().strip())
if ov:
    lines.append("# ---- HA role overrides (.ha-overrides, written by ha-failover promote) ----")
    for k,v in ov.items():
        if k!="HA_DATABASE_URL": lines.append(f"{k}={v}")
open(out,"w").write("\n".join(lines)+"\n")
print("from S1:", len(a), "keys; S2 overrides:", [k for k in KEEP_FROM_S2 if k in b], "missing:", missing, "ha-overrides:", sorted(ov))
