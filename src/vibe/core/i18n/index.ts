const currencySymbols = { USD: "$", EUR: "€", PLN: "zł" };
type Language = keyof typeof languageNames;

function region<const Code extends (typeof countries)[number]>(
  code: Code,
  language: Language,
  currency: keyof typeof currencySymbols,
  timezone: string,
  otherLanguages: Language[] = [],
): {
  code: Code;
  name: string;
  flag: string;
  language: Language;
  languages: Language[];
  langName: string;
  currency: keyof typeof currencySymbols;
  symbol: string;
  timezone: string;
} {
  const name =
    code === "GLOBAL"
      ? "Global"
      : (new Intl.DisplayNames(language, { type: "region" }).of(code) ?? code);
  const flag =
    code === "GLOBAL"
      ? "🌐"
      : Array.from(code, (letter) =>
          String.fromCodePoint(127397 + letter.charCodeAt(0)),
        ).join("");
  return {
    code,
    name,
    flag,
    language,
    languages: [language, ...otherLanguages],
    langName: languageNames[language],
    currency,
    symbol: currencySymbols[currency],
    timezone,
  };
}

